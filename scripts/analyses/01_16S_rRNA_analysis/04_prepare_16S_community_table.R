###############################################################################
# 16. BUILD COMBINED COUNT, TAXONOMY AND RELATIVE-ABUNDANCE TABLE
###############################################################################

make_combined_table <- function(
    count_table,
    taxonomy_table
) {

  selected_otus <- taxonomy_table$OTU

  missing_selected_otus <- setdiff(
    selected_otus,
    rownames(count_table)
  )

  if (length(missing_selected_otus) > 0) {
    stop(
      "Selected taxonomy OTUs are missing from the count table."
    )
  }

  count_table <- count_table[
    selected_otus,
    samples_all,
    drop = FALSE
  ]

  sample_read_totals <- colSums(
    count_table
  )

  if (any(sample_read_totals <= 0)) {
    stop(
      paste(
        "Samples with zero reads after filtering:",
        paste(
          names(sample_read_totals)[
            sample_read_totals <= 0
          ],
          collapse = ", "
        )
      )
    )
  }

  otu_levels <- gtools::mixedsort(
    selected_otus
  )

  counts_long <- count_table |>
    as.data.frame(
      check.names = FALSE
    ) |>
    tibble::rownames_to_column(
      "OTU"
    ) |>
    tidyr::pivot_longer(
      cols = dplyr::all_of(
        samples_all
      ),
      names_to = "Sample",
      values_to = "Count"
    ) |>
    dplyr::mutate(
      OTU = factor(
        .data$OTU,
        levels = otu_levels
      ),
      Sample = factor(
        .data$Sample,
        levels = samples_all
      ),
      Count = as.numeric(
        .data$Count
      )
    )

  combined_table <- counts_long |>
    dplyr::group_by(
      .data$Sample
    ) |>
    dplyr::mutate(
      Abundance = .data$Count /
        sum(
          .data$Count,
          na.rm = TRUE
        ),
      `Relative abundance` = .data$Abundance
    ) |>
    dplyr::ungroup() |>
    dplyr::mutate(
      OTU = as.character(
        .data$OTU
      )
    ) |>
    dplyr::left_join(
      taxonomy_table,
      by = "OTU"
    ) |>
    dplyr::mutate(
      Sample = factor(
        as.character(
          .data$Sample
        ),
        levels = samples_all
      ),
      OTU = factor(
        .data$OTU,
        levels = otu_levels
      ),
      Phylum = tidyr::replace_na(
        .data$Phylum,
        "NA"
      )
    ) |>
    dplyr::select(
      OTU,
      Sample,
      Count,
      Abundance,
      `Relative abundance`,
      Kingdom,
      Phylum,
      Class,
      Order,
      Family,
      Genus,
      Species,
      LCA_raw
    ) |>
    dplyr::arrange(
      .data$Sample,
      .data$OTU
    ) |>
    dplyr::mutate(
      OTU = as.character(
        .data$OTU
      ),
      Sample = as.character(
        .data$Sample
      )
    )

  expected_rows <- length(
    selected_otus
  ) * length(
    samples_all
  )

  if (nrow(combined_table) != expected_rows) {
    stop(
      paste0(
        "Unexpected number of rows in the combined table. Expected ",
        expected_rows,
        " but obtained ",
        nrow(combined_table),
        "."
      )
    )
  }

  combined_table
}

