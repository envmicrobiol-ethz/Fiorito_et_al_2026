# 19. CHECK RELATIVE-ABUNDANCE SUMS
###############################################################################

check_with_organelles <- combined_with_organelles |>
  dplyr::group_by(
    .data$Sample
  ) |>
  dplyr::summarise(
    table = "with_chloroplast_mitochondria",
    abundance_sum = sum(
      .data$Abundance,
      na.rm = TRUE
    ),
    .groups = "drop"
  ) |>
  dplyr::mutate(
    difference_from_one = .data$abundance_sum - 1
  )

check_clean <- combined_clean |>
  dplyr::group_by(
    .data$Sample
  ) |>
  dplyr::summarise(
    table = "without_chloroplast_mitochondria",
    abundance_sum = sum(
      .data$Abundance,
      na.rm = TRUE
    ),
    .groups = "drop"
  ) |>
  dplyr::mutate(
    difference_from_one = .data$abundance_sum - 1
  )

abundance_check <- dplyr::bind_rows(
  check_with_organelles,
  check_clean
)

if (any(
  abs(
    abundance_check$difference_from_one
  ) > 1e-10
)) {
  stop(
    "At least one sample relative-abundance total differs from 1."
  )
}

utils::write.table(
  abundance_check,
  file = abundance_check_file,
  sep = "\t",
  quote = FALSE,
  row.names = FALSE,
  na = "NA"
)

