###############################################################################
# 9. BUILD TAXONOMY STRINGS
#
# Taxonomic ranks are extracted by prefix rather than column position.
#
# This prevents a species label such as `s:uncultured_bacterium` from being
# interpreted as a phylum when intermediate ranks are absent.
###############################################################################

taxonomy_string <- apply(
  taxonomy_raw,
  1,
  function(x) {

    assigned_values <- x[
      !is.na(x) &
        x != ""
    ]

    paste(
      assigned_values,
      collapse = ";"
    )
  }
)

extract_rank <- function(
    taxonomy_string,
    prefix
) {

  pattern <- paste0(
    "(^|;)",
    prefix,
    ":([^;]+)"
  )

  extracted <- stringr::str_match(
    taxonomy_string,
    pattern
  )[
    ,
    3
  ]

  extracted <- trimws(
    extracted
  )

  extracted[
    is.na(extracted) |
      extracted == ""
  ] <- "unclassified"

  extracted
}

