###############################################################################
# 16S rRNA COMMUNITY-TABLE PREPARATION
#
# DESCRIPTION
#
# Combines the filtered 16S rRNA OTU count and taxonomy tables, removes
# non-bacterial and non-archaeal OTUs, removes chloroplast and mitochondrial
# sequences, and calculates OTU relative abundance within each sample.
#
# The resulting table is used to generate the phylum-level community-
# composition plots shown in Figure 1B and Figure 1D.
#
# INPUT
#
# Input files:
#   9.all.OTU_map.txt
#   9.all.OTU_tax.sintax.rf.txt
#
# Generated by:
#   scripts/analyses/01_16S_rRNA_analysis/
#   01_process_16S_amplicon_reads.sh
#
# The OTU count table must contain:
#   - OTU identifiers in the first column
#   - sample identifiers in the remaining columns
#
# The taxonomy table must contain:
#   - OTU identifiers in the first column
#   - taxonomy assignments containing the prefixes:
#       d:, p:, c:, o:, f:, g: and s:
#
# OUTPUT
#
# Primary output:
#   combined_otu_taxonomy_relative_abundance_2024.no_chloro_mito.xlsx
#
# Additional outputs:
#   combined_otu_taxonomy_relative_abundance_2024.with_chloro_mito.xlsx
#   chloroplast_mitochondria_removed_report.tsv
#   OTUs_removed_chloroplast_mitochondria_taxonomy.tsv
#   relative_abundance_sum_check.tsv
#   04_prepare_16S_community_table_sessionInfo.txt
#
# Both Excel files contain a worksheet named:
#   relative_abundance
#
# SAMPLE SELECTION
#
# The samples included in the final Figure 1B and Figure 1D community tables
# are listed explicitly below.
#
# BM.3.10 is intentionally excluded because it was not included in the final
# Figure 1B.
#
# USAGE
#
# Run from the directory containing the two input files:
#
# Rscript 04_prepare_16S_community_table.R
#
# Optional input and output directories:
#
# Rscript 04_prepare_16S_community_table.R \
#   path/to/input_directory \
#   path/to/output_directory
###############################################################################

