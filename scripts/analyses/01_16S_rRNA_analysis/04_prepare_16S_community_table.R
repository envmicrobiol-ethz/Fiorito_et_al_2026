###############################################################################
# 21. CREATE ORGANELLE-REMOVAL REPORT
###############################################################################

removed_report <- combined_with_organelles |>
  dplyr::group_by(
    .data$Sample
  ) |>
  dplyr::summarise(
    total_before = sum(
      .data$Abundance,
      na.rm = TRUE
    ),
    .groups = "drop"
  ) |>
  dplyr::left_join(
    combined_with_organelles |>
      dplyr::filter(
        .data$OTU %in% organelle_otus
      ) |>
      dplyr::group_by(
        .data$Sample
      ) |>
      dplyr::summarise(
        removed_abundance = sum(
          .data$Abundance,
          na.rm = TRUE
        ),
        removed_reads = sum(
          .data$Count,
          na.rm = TRUE
        ),
        .groups = "drop"
      ),
    by = "Sample"
  ) |>
  dplyr::mutate(
    removed_abundance = tidyr::replace_na(
      .data$removed_abundance,
      0
    ),
    removed_reads = tidyr::replace_na(
      .data$removed_reads,
      0
    ),
    percent_removed = .data$removed_abundance /
      .data$total_before * 100
  ) |>
  dplyr::arrange(
    dplyr::desc(
      .data$percent_removed
    )
  )

utils::write.table(
  removed_report,
  file = removed_report_file,
  sep = "\t",
  quote = FALSE,
  row.names = FALSE,
  na = "NA"
)

