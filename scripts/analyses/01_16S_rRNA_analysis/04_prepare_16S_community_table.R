###############################################################################
# 15. FORMAT TAXONOMY FOR OUTPUT
#
# Examples:
#   d:Bacteria       -> k__Bacteria
#   p:Acidobacteriota -> p__Acidobacteriota
###############################################################################

format_taxonomic_rank <- function(
    x,
    original_prefix,
    output_prefix,
    unknown = "NA"
) {

  x <- as.character(
    x
  )

  x[
    is.na(x) |
      x == "" |
      x == "unclassified"
  ] <- unknown

  prefixed_values <- grepl(
    "^[dkpcofgs]:",
    x
  )

  correct_prefix <- grepl(
    paste0(
      "^",
      original_prefix,
      ":"
    ),
    x
  )

  x[
    prefixed_values &
      !correct_prefix
  ] <- unknown

  x <- sub(
    paste0(
      "^",
      original_prefix,
      ":"
    ),
    paste0(
      output_prefix,
      "__"
    ),
    x
  )

  x
}

format_taxonomy_for_output <- function(
    taxonomy_table
) {

  taxonomy_table |>
    tibble::rownames_to_column(
      "OTU"
    ) |>
    dplyr::transmute(
      OTU = .data$OTU,
      Kingdom = format_taxonomic_rank(
        .data$domain,
        "d",
        "k"
      ),
      Phylum = format_taxonomic_rank(
        .data$phylum,
        "p",
        "p"
      ),
      Class = format_taxonomic_rank(
        .data$class,
        "c",
        "c"
      ),
      Order = format_taxonomic_rank(
        .data$order,
        "o",
        "o"
      ),
      Family = format_taxonomic_rank(
        .data$family,
        "f",
        "f"
      ),
      Genus = format_taxonomic_rank(
        .data$genus,
        "g",
        "g"
      ),
      Species = format_taxonomic_rank(
        .data$species,
        "s",
        "s"
      ),
      LCA_raw = .data$tax_string
    )
}

